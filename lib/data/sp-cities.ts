export function getMatchingCities(query: string, maxResults = 10): string[] {
  if (!query || query.trim() === '') return SP_CITIES.slice(0, maxResults);
  const normalized = query.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  return SP_CITIES.filter(city => {
    const cityNorm = city.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    return cityNorm.includes(normalized);
  }).slice(0, maxResults);
}
